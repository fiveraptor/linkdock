import assert from 'node:assert/strict';
import {normalize,same,merge,editItems} from '../dist/chrome/core.mjs';
const item=(id,title=id)=>({id,type:'bookmark',title,url:'https://example.com/'+id,parentId:null,position:0});
const a=item('a'),b=item('b');
assert.equal(same([a,b],[b,a]),true);
assert.deepEqual(merge([], [a],[b]).items.map(x=>x.id).sort(),['a','b']);
assert.deepEqual(merge([a],[{...a,title:'local'}],[{...a,url:'https://other.test'}]).items,[{...a,title:'local',url:'https://other.test'}]);
assert.equal(merge([a],[],[a]).items.length,0);
assert.equal(merge([a],[],[{...a,title:'remote'}]).conflicts.length,1);
assert.equal(merge([a],[{...a,title:'local'}],[{...a,title:'remote'}]).conflicts.length,1);
assert.deepEqual(merge([], [a],[a]).items,[a]);
const folder={id:'folder',type:'folder',title:'Folder',url:null,parentId:null,position:0};
assert.equal(merge([folder],[],[folder,{...a,parentId:'folder'}]).conflicts.length,1);
assert.throws(()=>normalize([{...folder,parentId:'folder'}]));
assert.throws(()=>normalize([{...a,url:'javascript:alert(1)'}]));
assert.throws(()=>normalize([a,a]));
assert.equal(editItems([folder,{...a,parentId:'folder'}],{kind:'delete',id:'folder'}).length,0);
assert.equal(editItems([a],{kind:'save',item:{...a,title:' Changed '}})[0].title,'Changed');
assert.equal(editItems([a,b],{kind:'move',id:'b',direction:-1}).find(x=>x.id==='b').position,0);
console.log('PASS: merge, deletion/edit conflicts, field merge, folder conflicts, validation and edit operations');
